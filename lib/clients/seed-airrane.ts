type Line = [ItemKind, string, string, number, string, number, string]

function sec(name: string, desc: string, lines: Line[]): QuoteSection {
  return {
    id: newId('s'),
    name,
    desc,
    option: false,
    items: lines.map(([kind, n, spec, qty, unit, price, note]) => ({ ...emptyItem(kind), name: n, spec, qty, unit, price, note })),
  }
}

