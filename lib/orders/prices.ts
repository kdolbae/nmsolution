/**
 * 발주처 단가표. 발주서 품목을 고를 때 쓰는 공급처별 단가(공급가, VAT 별도).
 * DB 를 쓰지 않는 타입·정리 함수만 두어 어드민 화면(브라우저)에서도 불러 쓴다. 저장·조회는 lib/orders/table.ts.
 *
 * - basis: m = 판넬처럼 길이(m)×수량×단가(폭 1,000 판넬은 ㎡ 단가와 같음), ea = 수량×단가
 * - 같은 품목이라도 날짜·출처가 다르면 줄을 따로 둔다(견적 단가와 거래명세서 단가를 같이 남김)
 */
export type PoPrice = {
  supplier: string
  category: string
  name: string
  spec: string
  unit: string
  basis: 'm' | 'ea'
  price: number
  date: string
  source: string
  note: string
}

export type PoPriceRow = PoPrice & { id: number }

export const PO_PRICE_CATEGORIES = ['판넬', '부자재', '후레싱', '도어', '위생 마감', '소모품', '운임', '기타']

export function emptyPrice(supplier = ''): PoPrice {
  return { supplier, category: '판넬', name: '', spec: '', unit: '장', basis: 'ea', price: 0, date: '', source: '', note: '' }
}

const str = (v: unknown, max = 300) => String(v ?? '').slice(0, max)

export function normalizePrice(raw: unknown): PoPrice {
  const r = (raw && typeof raw === 'object' ? raw : {}) as Record<string, unknown>
  const n = Number(r.price)
  return {
    supplier: str(r.supplier, 100),
    category: str(r.category, 40),
    name: str(r.name, 200),
    spec: str(r.spec, 300),
    unit: str(r.unit, 20),
    basis: r.basis === 'm' ? 'm' : 'ea',
    price: Number.isFinite(n) ? Math.max(0, Math.round(n)) : 0,
    date: str(r.date, 10),
    source: str(r.source, 100),
    note: str(r.note, 300),
  }
}

/** 발주처 이름과 단가표 공급처가 같은 회사인지. '(주)새롬판넬 화성공장' ↔ '새롬판넬' 처럼 괄호·공백·지점명을 무시하고 앞부분으로 맞춘다 */
export function sameSupplier(partyName: string, priceSupplier: string) {
  const key = (s: string) => s.replace(/\(.*?\)|㈜|주식회사|\s/g, '').replace(/패널/g, '판넬')
  const a = key(partyName)
  const b = key(priceSupplier)
  return !!a && !!b && (a.startsWith(b) || b.startsWith(a))
}

